"""Export folded float32 V2 weights + enrolled templates to an ESP32 header.

This is NOT INT8 quantization. Use the C++ reference runtime for matching
semantics before investigating weight and activation quantization.
"""
from pathlib import Path
import numpy as np
import torch
from .pipeline import load_templates, load_threshold
from .training import load_trained


def fused(conv, bn):
    weights = conv.weight.detach().cpu().numpy().astype(np.float64)
    gamma = bn.weight.detach().cpu().numpy().astype(np.float64)
    beta = bn.bias.detach().cpu().numpy().astype(np.float64)
    mean = bn.running_mean.detach().cpu().numpy().astype(np.float64)
    variance = bn.running_var.detach().cpu().numpy().astype(np.float64)
    slope = gamma / np.sqrt(variance + bn.eps)
    shape = (-1,) + (1,) * (weights.ndim - 1)
    out_w = weights * slope.reshape(shape)
    original_bias = (conv.bias.detach().cpu().numpy() if conv.bias is not None
                     else np.zeros_like(mean))
    out_b = beta + (original_bias - mean) * slope
    return out_w.astype(np.float32), out_b.astype(np.float32)


def to_cfloat(value):
    literal = format(float(np.float32(value)), ".9g")
    if "e" not in literal and "." not in literal:
        literal += ".0"
    return literal + "f"


def c_array(name, values):
    arr = np.asarray(values, dtype=np.float32).reshape(-1)
    rows = []
    for offset in range(0, arr.size, 8):
        rows.append("  " + ", ".join(to_cfloat(v) for v in arr[offset:offset + 8]) + ",")
    return f"static const float {name}[{arr.size}] = {{\n" + "\n".join(rows) + "\n};\n"


def export_header(checkpoint, templates, threshold_path, output):
    model = load_trained(checkpoint)
    centers = load_templates(checkpoint, templates)
    threshold = load_threshold(checkpoint, templates, threshold_path)
    arrays = [("gabor", model.gabor.detach().cpu().numpy())]
    w, b = fused(model.stem[0], model.stem[1])
    arrays.extend([("stem_w", w), ("stem_b", b)])
    for i, block in enumerate(model.blocks):
        w, b = fused(block.pointwise, block.bn)
        arrays.extend([
            (f"dw{i}_w", block.depthwise.weight.detach().cpu().numpy()),
            (f"pw{i}_w", w), (f"pw{i}_b", b)
        ])
    arrays.extend([
        ("fc_w", model.embedding.weight.detach().cpu().numpy()),
        ("fc_b", model.embedding.bias.detach().cpu().numpy()),
        ("centroids", centers)
    ])
    text = [
        "#pragma once",
        "// Auto-generated by python -m palm_v2.cli export. Do not edit.",
        "// Float32 weights, trained on person_01..person_04 in this fixed order.",
        "namespace palm_v2_weights {",
        "static constexpr int kInputSide = 64;",
        "static constexpr int kEmbeddingDim = 128;",
        f"static constexpr float kThreshold = {to_cfloat(threshold)};",
    ]
    text.extend(c_array(name, values) for name, values in arrays)
    text.append("} // namespace palm_v2_weights\n")
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(text), encoding="utf-8")
    return {"header": str(output), "size_bytes": output.stat().st_size,
            "threshold": threshold, "arrays": [name for name, _ in arrays]}
